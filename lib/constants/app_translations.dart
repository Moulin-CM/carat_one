import 'package:flutter/material.dart';
import '../services/localization_service.dart';

extension LocalizationExt on String {
  /// Translates the string based on the current language in LocalizationService.
  /// If the translation is not found, returns the original string.
  String get tr {
    try {
      if (LocalizationService.instanceOrNull == null) return this;
      final lang = LocalizationService.instanceOrNull!.currentLanguage;
      return AppTranslations.translations[lang]?[this] ?? this;
    } catch (e) {
      return this;
    }
  }
}

